/* Every town with no minimum lot size (2026-10-16, Matthew: "run them all at no filters at all in terms of lot sizes since we are
   transitioning to a lot more aeration ... keep the 10 acre cap"). Writes run-allsizes-2026-10-16.sh: closest to Englewood first, one
   town at a time (one parcel-heavy job on gis.colorado.gov), each town: pull again with --min-acres=0, neighbourhoods, lawns, trees,
   values, office lookup, rebuild, upload, assignments carried to the redrawn neighbourhoods.
   - towns whose pull is recorded (batch 4 / batch 5): the same command with --min-acres=0
   - the older towns (no recorded command): the county + their own centre, reach and situs cities, then kept to their old footprint
   - El Paso (Monument, Colorado Springs ...): left for a second pass (a different pull script)
   Highlands Ranch is done (run-hr-all-2026-10-16.sh).   node make-allsizes.cjs */
const fs = require('fs');
const idx = require('../../app/data/rounds/index.json');
const EL_PASO = ['monument', 'palmer-lake', 'black-forest', 'cs-northeast', 'cs-southeast', 'cs-northwest', 'cs-southwest', 'security-widefield', 'fountain', 'walden'];
const DONE = ['highlands-ranch'];
const COUNTIES = {
  'castle-rock': ['DOUGLAS'], larkspur: ['DOUGLAS'], sedalia: ['DOUGLAS'], franktown: ['DOUGLAS'], parker: ['DOUGLAS'], 'castle-pines': ['DOUGLAS'], 'lone-tree': ['DOUGLAS'],
  'woodland-park': ['TELLER'], divide: ['TELLER'], florissant: ['TELLER'], 'cripple-creek': ['TELLER'],
  arvada: ['JEFFERSON', 'ADAMS'], centennial: ['ARAPAHOE'], thornton: ['ADAMS', 'WELD'], windsor: ['WELD', 'LARIMER'], erie: ['WELD', 'BOULDER'], 'commerce-city': ['ADAMS'],
  denver: ['DENVER'], 'south-denver': ['DENVER'], boulder: ['BOULDER'], aurora: ['ARAPAHOE', 'ADAMS', 'DOUGLAS'], englewood: ['ARAPAHOE'], 'greenwood-village': ['ARAPAHOE'],
  'cherry-hills-village': ['ARAPAHOE'], sheridan: ['ARAPAHOE'], littleton: ['ARAPAHOE', 'JEFFERSON', 'DOUGLAS'], lakewood: ['JEFFERSON'], 'wheat-ridge': ['JEFFERSON'],
  edgewater: ['JEFFERSON'], golden: ['JEFFERSON'], westminster: ['ADAMS', 'JEFFERSON'],
};
const parse = (line) => { const out = []; let cur = '', q = false; for (let i = 0; i < line.length; i++) { const c = line[i]; if (q) { if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; } else if (c === '"') q = true; else if (c === ',') { out.push(cur); cur = ''; } else cur += c; } out.push(cur); return out; };
const rec = ['run-batch4-2026-10-16.sh', 'run-batch5-2026-10-15.sh'].filter((f) => fs.existsSync(f)).map((f) => fs.readFileSync(f, 'utf8'));
const recorded = (t) => {
  for (const s of rec) {
    const pulls = s.split('\n').filter((l) => new RegExp(`^\\s*step pull-${t}(-\\d+)? node build-walklist-co\\.mjs `).test(l)).map((l) => l.trim().replace(/--min-acres=[0-9.]+/, '--min-acres=0'));
    if (!pulls.length) continue;
    const merge = s.split('\n').find((l) => l.includes(`node merge-walklists.mjs ${t}.csv `));
    return { pulls, merge: merge ? merge.trim() : '' };
  }
  return null;
};
const EN = [39.6533, -104.9916];
const towns = idx.regions.filter((r) => !r.admin && !/^hailrep|^(mckinney|plano|frisco)$/.test(r.key) && !EL_PASO.includes(r.key) && !DONE.includes(r.key))
  .map((r) => ({ k: r.key, label: r.label, d: r.c ? Math.hypot((r.c[0] - EN[0]) * 69, (r.c[1] - EN[1]) * 53.3) : 99 }))
  .sort((a, b) => a.d - b.d);
let out = `#!/bin/bash
# GENERATED by make-allsizes.cjs (2026-10-16): every town with no minimum lot size, closest to Englewood first. See that file.
cd "/c/Users/Surge Inc/Desktop/claude test 2/traverse/data-pipeline/door-territory"
L=logs-allsizes; mkdir -p "$L"
step() { local name=$1; shift; echo "$(date +%H:%M:%S) start $name"; ( "$@" ) > "$L/$name.log" 2>&1; local rc=$?; echo "$(date +%H:%M:%S) end   $name (exit $rc) $(tail -1 "$L/$name.log" | tr '\\r' '\\n' | tail -1 | cut -c1-150)"; return $rc; }
SSID=$(netsh wlan show interfaces 2>/dev/null | tr -d '\\r' | awk -F': ' '/^ *SSID/{print $2; exit}')
case "$SSID" in *iPhone*|*iphone*) echo "on the hotspot ($SSID) - not starting"; exit 1;; esac
echo "$(date +%T) network: \${SSID:-wired}"
bash hotspot-watchdog2.sh run-allsizes > "$L/watchdog.log" 2>&1 &
cat remap-assign.py | bash /c/Users/SURGEI~1/.ssh/sg.sh trav 'cat > ~/remap-assign.py && echo remap-ready'
rows() { [ -s "$1" ] && echo $(( $(wc -l < "$1") - 1 )) || echo 0; }
town() {   # town key, then the pull lines run by the caller
  :
}
`;
let n = 0, nd = 0;
for (const t of towns) {
  const k = t.k, r = recorded(k);
  let pull = '';
  if (r) {
    pull = r.pulls.map((p) => '  ' + p).join('\n') + '\n' + (r.merge ? '  ' + r.merge + '\n' : '');
  } else {
    const cs = COUNTIES[k];
    if (!cs || !fs.existsSync(k + '.csv')) { out += `echo "$(date +%T) skip ${k}: no county or no old list"\n`; continue; }
    const L = fs.readFileSync(k + '.csv', 'utf8').split(/\r?\n/).filter(Boolean), h = parse(L[0]), ci = h.indexOf('city'), la = h.indexOf('lat'), lo = h.indexOf('lon');
    let sy = 0, sx = 0, m = 0; const cnt = {};
    const pts = [];
    for (const l of L.slice(1)) { const p = parse(l), y = +p[la], x = +p[lo]; if (!isFinite(y) || !isFinite(x)) continue; sy += y; sx += x; m++; pts.push([y, x]); const c = (p[ci] || '').trim().toUpperCase(); if (c) cnt[c] = (cnt[c] || 0) + 1; }
    const cy = sy / m, cx = sx / m;
    let far = 0; for (const [y, x] of pts) far = Math.max(far, Math.hypot((y - cy) * 69, (x - cx) * 53.3));
    const radius = Math.min(15, Math.ceil((far + 0.4) * 10) / 10);
    const cities = Object.keys(cnt).filter((c) => cnt[c] >= m * 0.005).sort();
    const tag = (c) => c.toLowerCase();
    const outs = cs.map((c) => `${k}-${tag(c)}.csv`);
    pull = cs.map((c, i) => `  step pull-${k}${cs.length > 1 ? '-' + (i + 1) : ''} node build-walklist-co.mjs --county='${c}' --lat=${cy.toFixed(4)} --lon=${cx.toFixed(4)} --radius=${radius} --min-acres=0 --cities='${cities.join(',')}' --out=${outs[i]}`).join('\n') + '\n';
    pull += cs.length > 1 ? `  node merge-walklists.mjs ${k}.csv $(ls ${outs.join(' ')} 2>/dev/null) > "$L/merge-${k}.log" 2>&1\n` : `  mv -f ${outs[0]} ${k}.csv\n`;
    pull += `  [ -s ${k}.csv ] && step footprint-${k} node filter-footprint.mjs ${k}.csv ${k}.csv.bak-allsizes 0.35\n`;
    nd++;
  }
  n++;
  out += `
# ${t.label}, ${t.d.toFixed(1)} mi${r ? '' : ' (pull rebuilt from its old list)'}
echo "$(date +%T) == ${k} (${n})"
cp ${k}.csv ${k}.csv.bak-allsizes 2>/dev/null; cp ${k}-areas.json ${k}-areas.json.bak-allsizes 2>/dev/null
OLD=$(rows ${k}.csv.bak-allsizes)
${pull}NEW=$(rows ${k}.csv)
if [ "$NEW" -le "$OLD" ]; then echo "$(date +%T) ${k}: not bigger ($OLD -> $NEW), old files back"; cp ${k}.csv.bak-allsizes ${k}.csv 2>/dev/null; cp ${k}-areas.json.bak-allsizes ${k}-areas.json 2>/dev/null
else
  echo "$(date +%T) ${k}: $OLD -> $NEW doors"
  step areas-${k} node build-walklist-pdf.mjs ${k}.csv --no-pdf
  step lawn-${k} bash -c "cd lawn-trial && node sample-lawn.mjs --town=${k} --conc=16"
  step compact-${k} bash -c "cd lawn-trial && node sample-lawn-compact.mjs --town=${k} --conc=6"
  step trees-${k} bash -c "cd tree-zones && node sample-trees.mjs --town=${k} --conc=6"
  step value-${k} node sample-value.mjs --only=${k}
  step lookup-${k} node build-lookup.mjs ${k}
  step rounds-${k} node build-rounds-data.mjs
  bash upload-towns-sixfold.sh allsizes-${k} ${k}
  bash /c/Users/SURGEI~1/.ssh/sg.sh trav "python3 ~/remap-assign.py ${k} ~/upload-backups/before-allsizes-${k}.tgz" < /dev/null
fi
`;
}
out += `echo "$(date +%T) all done"\n`;
fs.writeFileSync('run-allsizes-2026-10-16.sh', out);
console.log('towns', n, '| recorded pulls', n - nd, '| rebuilt from old lists', nd, '| order:', towns.map((t) => t.k).join(' '));
