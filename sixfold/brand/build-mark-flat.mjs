/* Sixfold — the FLAT Ridge mark: the merch master.
   Built 2026-09-16 from the finding in operations/crew-shirt-spec.md: the Ridge
   mark's four peaks carry fill-opacity (0.4 / 0.6 / 0.82 / 1), and a screen is
   ink or no ink. Flattening every peak to solid merges them into one silhouette.

   This version keeps the layering as GEOMETRY instead of transparency:
     - every peak is a solid fill
     - each peak in front cuts a knockout gap (no ink) into the peaks behind it,
       so the four ridges still read as four
     - the tree cuts the same gap into the peak behind it
     - roots dropped (the shirt spec: their strokes fall under what a screen holds)
     - trunk widened 3.2 -> 4.2 units so it survives at sleeve size (>= 0.03 in at 3 in)
   The gaps are real subtracted paths (polygon-clipping), not masks or strokes, so
   a printer gets plain filled shapes. Two outputs:
     sixfold-mark-ridge-flat.svg       two-colour: ember peaks, moss tree + ground
     sixfold-mark-ridge-flat-mono.svg  one ink, currentColor — shirts, stickers, engraving
   Same viewBox as the master (0 0 100 116) minus the root area, so it drops into
   any lockup that used the original.

   Run:  node sixfold/brand/build-mark-flat.mjs */
import pc from 'polygon-clipping';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const GAP = 1.6;               // knockout width in viewBox units (0.05 in at a 3 in print)
const TRUNK_W = 4.2;

// Geometry from sixfold-mark-ridge.svg, back (P1) to front (P4)
const peaks = [
  [[18, 84], [36, 48], [54, 84]],
  [[30, 84], [50, 38], [70, 84]],
  [[44, 84], [66, 26], [88, 84]],
  [[60, 84], [79, 14], [98, 84]],
];
const tree = [
  [[22, 69], [9.5, 81.5], [34.5, 81.5]],
  [[22, 62], [12, 74], [32, 74]],
  [[22, 55.5], [14.5, 66.5], [29.5, 66.5]],
];
const trunkX = 22 - TRUNK_W / 2;
const trunk = [[trunkX, 77], [trunkX + TRUNK_W, 77], [trunkX + TRUNK_W, 84.5], [trunkX, 84.5]];
const ground = [[4, 86], [96, 86], [96, 91], [4, 91]];

// Dilate a convex polygon by d: push every edge outward along its normal and
// re-intersect neighbouring edges. Good enough for triangles and rectangles.
function dilate(poly, d) {
  const n = poly.length;
  // ensure counter-clockwise (shoelace > 0) so "outward" is consistent
  let area = 0;
  for (let i = 0; i < n; i++) { const [x1, y1] = poly[i], [x2, y2] = poly[(i + 1) % n]; area += x1 * y2 - x2 * y1; }
  const p = area < 0 ? [...poly].reverse() : poly;
  const lines = p.map((a, i) => {
    const b = p[(i + 1) % n];
    const dx = b[0] - a[0], dy = b[1] - a[1], L = Math.hypot(dx, dy);
    const nx = dy / L, ny = -dx / L;          // outward normal for CCW in y-down coords
    return { a: [a[0] + nx * d, a[1] + ny * d], b: [b[0] + nx * d, b[1] + ny * d] };
  });
  const out = [];
  for (let i = 0; i < n; i++) {
    const l1 = lines[(i + n - 1) % n], l2 = lines[i];
    out.push(intersect(l1.a, l1.b, l2.a, l2.b));
  }
  return out;
}
function intersect(p1, p2, p3, p4) {
  const d = (p1[0] - p2[0]) * (p3[1] - p4[1]) - (p1[1] - p2[1]) * (p3[0] - p4[0]);
  const t = ((p1[0] - p3[0]) * (p3[1] - p4[1]) - (p1[1] - p3[1]) * (p3[0] - p4[0])) / d;
  return [p1[0] + t * (p2[0] - p1[0]), p1[1] + t * (p2[1] - p1[1])];
}

const ring = (poly) => [poly];                              // polygon-clipping shape
const treeUnion = pc.union(ring(tree[0]), ring(tree[1]), ring(tree[2]), ring(trunk));
const treeDilated = pc.union(...[...tree, trunk].map(t => ring(dilate(t, GAP))));

// Each peak minus everything in front of it (dilated), minus the tree (dilated)
const cutPeaks = peaks.map((pk, i) => {
  let shape = ring(pk);
  for (let j = i + 1; j < peaks.length; j++) shape = pc.difference(shape, ring(dilate(peaks[j], GAP)));
  shape = pc.difference(shape, treeDilated);
  return shape;
});

const f = (v) => Number(v.toFixed(2));
const toPath = (multi) => multi.map(poly => poly.map(r => 'M' + r.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'Z').join('')).join('');
const peaksPath = cutPeaks.map(toPath).join('');
const treePath = toPath(treeUnion);
const groundPath = toPath([ring(ground)]);   // wrap: a single Polygon, not a MultiPolygon

const head = (label) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 96" width="500" height="480" role="img" aria-label="${label}">
  <title>${label}</title>
  <!-- Generated by build-mark-flat.mjs — do not hand-edit; change the source geometry there. -->`;

writeFileSync(join(HERE, 'sixfold-mark-ridge-flat.svg'), `${head('Sixfold mark, Ridge — flat (print master)')}
  <path fill="#E4703A" fill-rule="evenodd" d="${peaksPath}"/>
  <path fill="#8AA07A" fill-rule="evenodd" d="${treePath}"/>
  <path fill="#8AA07A" d="${groundPath}"/>
</svg>
`);
writeFileSync(join(HERE, 'sixfold-mark-ridge-flat-mono.svg'), `${head('Sixfold mark, Ridge — flat, one colour')}
  <path fill="currentColor" fill-rule="evenodd" d="${peaksPath}${treePath}${groundPath}"/>
</svg>
`);
console.log(`wrote sixfold-mark-ridge-flat.svg and -mono.svg  (gap ${GAP} u, trunk ${TRUNK_W} u; ${peaksPath.length + treePath.length} chars of path)`);
