/* Sixfold — vehicle magnet proof sheet.

   Why this file exists: proof.png is what actually gets sent to the crew, and
   until now it was regenerated by "the snippet in the session notes" (README,
   line 56). A snippet in a chat log is not a build step — it went stale the
   moment the magnets were rebuilt onto palette A on 2026-09-28, and a proof
   showing the OLD orange artwork is worse than no proof at all.

   Rasterises the three magnet HTML pages in print media (so the screen-only
   trim/safe guides do not appear) and stacks them on one Pine sheet.

   Run:  node sixfold/brand/vehicle/build-proof.mjs
   Then LOOK at proof.png. It is the thing a human sees.                      */
import { spawn } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';

const PORT = process.argv[2] === 'fire' ? 9379 : 9378;   // separate ports so both can run
const HERE = dirname(fileURLToPath(import.meta.url));
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const PINE = { r: 14, g: 21, b: 18, alpha: 1 };
/* Two sheets, one per colourway, rather than six on one strip: the point of the
   proof is to choose BETWEEN the families, and that is easier side by side than
   scrolling one long column. Pass 'fire' to build the ember sheet. */
const FAMILY = process.argv[2] === 'fire' ? 'fire' : 'green';
const PAGES = FAMILY === 'fire'
  ? ['magnet-24x12-fire', 'magnet-24x18-fire', 'magnet-24x12-fire-light']
  : ['magnet-24x12', 'magnet-24x18', 'magnet-24x12-light'];
const OUT_NAME = FAMILY === 'fire' ? 'proof-fire.png' : 'proof.png';
const WIDTH = 1500;          // px per magnet in the sheet
const PAD = 40;

const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const prof = mkdtempSync(join(tmpdir(), 'proof-'));
const ch = spawn(CHROME, ['--headless=new', `--remote-debugging-port=${PORT}`,
  `--user-data-dir=${prof}`, '--no-first-run', '--disable-gpu', '--hide-scrollbars',
  '--force-color-profile=srgb'], { stdio: 'ignore' });

let ws, id = 0;
const pending = new Map();
for (let i = 0; i < 60; i++) {
  try {
    const t = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
    const pg = t.find((x) => x.type === 'page');
    if (pg) { ws = new WebSocket(pg.webSocketDebuggerUrl); break; }
  } catch { /* chrome not up yet */ }
  await wait(250);
}
await new Promise((r) => ws.addEventListener('open', r));
ws.addEventListener('message', (e) => {
  const m = JSON.parse(e.data);
  if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); }
});
const cmd = (method, params = {}) => new Promise((r) => {
  const n = ++id; pending.set(n, r); ws.send(JSON.stringify({ id: n, method, params }));
});

await cmd('Page.enable');
// print media: the trim/safe dashes are @media screen only, and a proof must show
// what prints, not the guides.
await cmd('Emulation.setEmulatedMedia', { media: 'print' });

const shots = [];
for (const name of PAGES) {
  const url = pathToFileURL(join(HERE, `${name}.html`)).href;
  // Each magnet declares its own @page size in inches; measure the body rather
  // than assuming, so 24x12 and 24x18 both come out right.
  await cmd('Emulation.setDeviceMetricsOverride', { width: 2000, height: 1200, deviceScaleFactor: 1, mobile: false });
  await cmd('Page.navigate', { url });
  await wait(900);
  const { result } = await cmd('Runtime.evaluate', {
    returnByValue: true,
    expression: 'JSON.stringify({w: document.body.offsetWidth, h: document.body.offsetHeight})',
  });
  const { w, h } = JSON.parse(result.value);
  const scale = WIDTH / w;
  // DSF stays 1: the clip's own scale does the resizing. Setting both multiplies
  // them together and the shot comes out scale^2 of the intended size.
  await cmd('Emulation.setDeviceMetricsOverride', { width: Math.ceil(w), height: Math.ceil(h), deviceScaleFactor: 1, mobile: false });
  await wait(400);
  const { data } = await cmd('Page.captureScreenshot', {
    format: 'png', captureBeyondViewport: true,
    clip: { x: 0, y: 0, width: w, height: h, scale },
  });
  const buf = Buffer.from(data, 'base64');
  const meta = await sharp(buf).metadata();
  shots.push({ name, buf, w: meta.width, h: meta.height });
  console.log(`  ${name}  ${meta.width}x${meta.height}`);
}

ws.close(); ch.kill(); await wait(300);
try { rmSync(prof, { recursive: true, force: true }); } catch { /* windows lock */ }

// Measured, not assumed: if a shot comes back a different size than asked for,
// the sheet should still fit it rather than leave a band of empty Pine.
const sheetW = Math.max(...shots.map((s) => s.w)) + PAD * 2;
const sheetH = shots.reduce((a, s) => a + s.h + PAD, PAD);
const out = join(HERE, OUT_NAME);
let y = PAD;
const composite = shots.map((s) => { const c = { input: s.buf, left: PAD, top: y }; y += s.h + PAD; return c; });
await sharp({ create: { width: sheetW, height: sheetH, channels: 4, background: PINE } })
  .composite(composite).png().toFile(out);
console.log(`\n${OUT_NAME}  ${sheetW}x${sheetH}  (${shots.length} magnets, top to bottom: ${PAGES.join(', ')})`);
